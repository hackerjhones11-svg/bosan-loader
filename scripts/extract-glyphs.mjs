// Extracts the exact Cormorant Garamond Medium outlines used by the intro
// wordmark into src/intro/glyphData.ts (y-down, baseline at 0, font units).
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import opentype from 'opentype.js';

const require = createRequire(import.meta.url);
const fontPath = require.resolve(
  '@fontsource/cormorant-garamond/files/cormorant-garamond-latin-500-normal.woff',
);
const buf = fs.readFileSync(fontPath);
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));

const chars = ['B', 'O', 'S', 'A', 'N', 'H', 'I', 'L'];
const r = (n) => Math.round(n * 100) / 100;

const glyphs = {};
for (const ch of chars) {
  const g = font.charToGlyph(ch);
  const p = g.getPath(0, 0, font.unitsPerEm);
  const bb = p.getBoundingBox();
  glyphs[ch] = {
    d: p.toPathData(2),
    advance: g.advanceWidth,
    bounds: [r(bb.x1), r(bb.y1), r(bb.x2), r(bb.y2)],
  };
}

const out = `// Generated by scripts/extract-glyphs.mjs — do not edit by hand.
// Cormorant Garamond Medium (SIL Open Font License 1.1), units per em ${font.unitsPerEm}.
// Paths are y-down with the baseline at y = 0.

export const UNITS_PER_EM = ${font.unitsPerEm};
export const CAP_HEIGHT = ${font.tables.os2.sCapHeight};
export const SPACE_ADVANCE = ${font.charToGlyph(' ').advanceWidth};

export type GlyphChar = ${chars.map((c) => `'${c}'`).join(' | ')};

export interface GlyphRecord {
  d: string;
  advance: number;
  /** [minX, minY, maxX, maxY] */
  bounds: [number, number, number, number];
}

export const GLYPHS: Record<GlyphChar, GlyphRecord> = ${JSON.stringify(glyphs, null, 2)};
`;

const dest = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../src/intro/glyphData.ts');
fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.writeFileSync(dest, out);
console.log('wrote', dest);
